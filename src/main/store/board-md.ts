import { sortAttention } from '../../shared/priority';
import type { State, Task, TaskStatus } from '../../shared/types';
import { totalCost } from '../usage/monitor';

function cell(s: string | undefined): string {
  return (s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').slice(0, 120);
}
function hhmm(epochS?: number): string {
  if (!epochS) return '—';
  const d = new Date(epochS * 1000);
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
}

/** Deterministic board.md (SPEC §4.5). Never read back by the app. */
export function renderBoard(s: State, now = new Date()): string {
  const open = sortAttention(Object.values(s.attention).filter((a) => a.status === 'open'), now.getTime());
  const snoozed = Object.values(s.attention).filter((a) => a.status === 'snoozed').length;
  const urgent = open.filter((a) => a.urgency === 'urgent').length;
  const p = s.usage.plan;
  const lines: string[] = [];
  lines.push(`<!-- GENERATED by agentboard from events.jsonl seq ${s.seq} — do not edit -->`);
  lines.push('# agentboard board', '');
  lines.push(
    `Usage: 5h ${p.fiveHour ? `${Math.round(p.fiveHour.usedPct)}% (resets ${hhmm(p.fiveHour.resetsAt)})` : '—'} · 7d ${p.sevenDay ? `${Math.round(p.sevenDay.usedPct)}%` : '—'} · spawning: ${s.usage.paused ? 'PAUSED' : 'ACTIVE'}   |   Needs you: ${open.length} open${urgent ? ` (${urgent} urgent)` : ''}${snoozed ? `, ${snoozed} later` : ''}`,
    '',
  );
  lines.push('## Needs you', '', '| ID | Task | Worker | Urgent | Irrev. | Question | Recommendation |', '|---|---|---|---|---|---|---|');
  for (const a of open) {
    const rec = a.recommendation ? a.options.find((o) => o.key === a.recommendation!.optionKey)?.label ?? a.recommendation.optionKey : '';
    lines.push(`| ${a.id} | ${a.task ?? ''} | ${a.workerName ?? ''} | ${a.urgency === 'urgent' ? '‼' : ''} | ${a.irreversible ? 'yes' : ''} | ${cell(a.question)} | ${cell(rec)} |`);
  }
  const workerName = (t: Task) => (t.worker ? s.sessions[s.workers[t.worker]]?.name ?? t.worker : '');
  const section = (title: string, statuses: TaskStatus[], limit?: number) => {
    let tasks = Object.values(s.tasks).filter((t) => statuses.includes(t.status));
    tasks.sort((a, b) => (statuses.length > 1 || limit ? b.updatedAt.localeCompare(a.updatedAt) : a.priority - b.priority || a.id.localeCompare(b.id, undefined, { numeric: true })));
    if (limit) tasks = tasks.slice(0, limit);
    lines.push('', `## ${title}`, '', '| T | Title | Worker | Branch/Workspace | Last progress | Est. cost | Updated |', '|---|---|---|---|---|---|---|');
    for (const t of tasks) {
      const sess = t.worker ? s.sessions[s.workers[t.worker]] : undefined;
      const cost = sess ? totalCost(s.usage.perSession[sess.id]) : undefined;
      lines.push(`| ${t.id} | ${cell(t.title)} | ${workerName(t)} | ${cell(t.branch ?? t.workspace)} | ${cell(t.lastProgress?.summary)} | ${cost !== undefined ? `$${cost.toFixed(2)}` : ''} | ${t.updatedAt.slice(0, 16).replace('T', ' ')} |`);
    }
  };
  section('Running', ['running']);
  section('Blocked', ['blocked']);
  section('Review (awaiting merge decision)', ['review']);
  section('Queued / Planned / Inbox', ['queued', 'planned', 'inbox']);
  section('Done (last 20)', ['done'], 20);
  section('Failed / Cancelled (last 10)', ['failed', 'cancelled'], 10);
  return lines.join('\n') + '\n';
}
